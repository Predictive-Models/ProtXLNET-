import torch
import pandas as pd
import numpy as np
from transformers import AutoTokenizer, AutoModel
from tqdm import tqdm

# -------------------------------
# Configuration
# -------------------------------
INPUT_CSV  = "test_filtered_0.8.csv"
OUTPUT_CSV = "mouse_protxlnet_len100_embeddings.csv"
MODEL_NAME = "Rostlab/prot_xlnet"
MAX_LEN = 100
BATCH_SIZE = 256
DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("Using device:", DEVICE)

# -------------------------------
# Load tokenizer & model
# -------------------------------
tokenizer = AutoTokenizer.from_pretrained(
    MODEL_NAME,
    do_lower_case=False,
    use_fast=False
)
model = AutoModel.from_pretrained(MODEL_NAME)
model.to(DEVICE)
model.eval()

# -------------------------------
# Helper functions
# -------------------------------
def space_sequence(seq):
    return " ".join(list(seq))

def tokenize_batch(seqs):
    seqs = [space_sequence(s) for s in seqs]
    tokens = tokenizer(
        seqs,
        padding=True,
        truncation=True,
        max_length=MAX_LEN,
        return_tensors="pt"
    )
    return {k: v.to(DEVICE) for k, v in tokens.items()}

# -------------------------------
# Load data
# -------------------------------
df = pd.read_csv(INPUT_CSV)

seq1_list = df["seq1"].astype(str).tolist()
seq2_list = df["seq2"].astype(str).tolist()
labels    = df["label"].values

# -------------------------------
# Extract ProtXLNet embeddings
# -------------------------------
all_embeddings = []

with torch.no_grad():
    for i in tqdm(range(0, len(df), BATCH_SIZE)):
        batch_seq1 = seq1_list[i:i+BATCH_SIZE]
        batch_seq2 = seq2_list[i:i+BATCH_SIZE]

        tok1 = tokenize_batch(batch_seq1)
        tok2 = tokenize_batch(batch_seq2)

        emb1 = model(**tok1).last_hidden_state.mean(dim=1)
        emb2 = model(**tok2).last_hidden_state.mean(dim=1)

        combined = torch.cat([emb1, emb2], dim=1)  # (B, 2048)
        all_embeddings.append(combined.cpu().numpy())

# Stack all batches
X = np.vstack(all_embeddings)

# -------------------------------
# Save to CSV
# -------------------------------
feature_cols = [f"feat_{i+1}" for i in range(X.shape[1])]
out_df = pd.DataFrame(X, columns=feature_cols)
out_df["label"] = labels

out_df.to_csv(OUTPUT_CSV, index=False)

print(f"✅ ProtXLNet embeddings (len=100) saved to: {OUTPUT_CSV}")
print("Feature dimension per sample:", X.shape[1])