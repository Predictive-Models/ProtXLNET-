# BiGRU-only publication pipeline (template adapted from user's script)
import os, warnings
warnings.filterwarnings("ignore")
import numpy as np, pandas as pd, matplotlib.pyplot as plt
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score,precision_score,recall_score,f1_score,roc_auc_score,confusion_matrix,matthews_corrcoef,roc_curve,precision_recall_curve
from imblearn.over_sampling import SMOTE
import torch
import torch.nn as nn
from torch.utils.data import TensorDataset,DataLoader
from lime.lime_tabular import LimeTabularExplainer

DEVICE=torch.device("cuda" if torch.cuda.is_available() else "cpu")
SAVE_DIR="Publication_Results_BiGRU"; os.makedirs(SAVE_DIR,exist_ok=True)

train_file="SVM RFE 20 Human train.csv"
test_file="SVM RFE Human Independent.csv"
train_df=pd.read_csv(train_file); test_df=pd.read_csv(test_file)

X=train_df.drop(columns=["label"]); y=train_df["label"]
X,y=SMOTE(random_state=42).fit_resample(X,y)
X_train,X_test=X,test_df.drop(columns=["label"])
y_train=pd.Series(y); y_test=test_df["label"]

scaler=StandardScaler()
X_train=scaler.fit_transform(X_train)
X_test=scaler.transform(X_test)
feature_names=list(train_df.drop(columns=["label"]).columns)

class BiGRU(nn.Module):
    def __init__(self,input_dim,h=128,d=0.5):
        super().__init__()
        self.gru=nn.GRU(input_dim,h,batch_first=True,bidirectional=True)
        self.drop=nn.Dropout(d)
        self.fc=nn.Linear(h*2,2)
    def forward(self,x):
        x=x.unsqueeze(1)
        o,_=self.gru(x)
        return self.fc(self.drop(o[:,-1,:]))

model=BiGRU(X_train.shape[1]).to(DEVICE)
opt=torch.optim.Adam(model.parameters(),lr=5e-4,weight_decay=1e-5)
loss_fn=nn.CrossEntropyLoss()
loader=DataLoader(TensorDataset(torch.tensor(X_train,dtype=torch.float32),torch.tensor(y_train.values,dtype=torch.long)),batch_size=32,shuffle=True)
losses=[]
for e in range(20):
    model.train(); run=0
    for xb,yb in loader:
        xb,yb=xb.to(DEVICE),yb.to(DEVICE)
        opt.zero_grad()
        out=model(xb)
        loss=loss_fn(out,yb)
        loss.backward(); opt.step()
        run+=loss.item()
    losses.append(run/len(loader))
    print(e+1,losses[-1])

plt.plot(losses); plt.xlabel("Epoch"); plt.ylabel("Loss")
plt.savefig(os.path.join(SAVE_DIR,"BiGRU_Training_Loss.png")); plt.close()

model.eval()
with torch.no_grad():
    probs=torch.softmax(model(torch.tensor(X_test,dtype=torch.float32).to(DEVICE)),dim=1)[:,1].cpu().numpy()

p,r,t=precision_recall_curve(y_test,probs)
f=2*p*r/(p+r+1e-10)
thr=t[np.argmax(f)] if len(t)>0 else 0.5
pred=(probs>=thr).astype(int)

acc=accuracy_score(y_test,pred)
pre=precision_score(y_test,pred)
rec=recall_score(y_test,pred)
f1=f1_score(y_test,pred)
auc=roc_auc_score(y_test,probs)
mcc=matthews_corrcoef(y_test,pred)
tn,fp,fn,tp=confusion_matrix(y_test,pred).ravel()
spec=tn/(tn+fp)

pd.DataFrame([{"Model":"BiGRU","Accuracy":acc,"Precision":pre,"Recall":rec,"Specificity":spec,"F1":f1,"MCC":mcc,"AUC":auc}]).to_excel(os.path.join(SAVE_DIR,"BiGRU_Metrics.xlsx"),index=False)

fpr,tpr,_=roc_curve(y_test,probs)
plt.plot(fpr,tpr,label=f"AUC={auc:.3f}")
plt.plot([0,1],[0,1],'k--'); plt.legend()
plt.savefig(os.path.join(SAVE_DIR,"BiGRU_ROC_Curve.png")); plt.close()

cm=confusion_matrix(y_test,pred)
plt.imshow(cm); plt.colorbar()
plt.savefig(os.path.join(SAVE_DIR,"BiGRU_Confusion_Matrix.png")); plt.close()

def predict_fn(x):
    with torch.no_grad():
        return torch.softmax(model(torch.tensor(x,dtype=torch.float32).to(DEVICE)),dim=1).cpu().numpy()

exp=LimeTabularExplainer(X_train,feature_names=feature_names,class_names=["Non","Interacting"],mode="classification").explain_instance(X_test[0],predict_fn,num_features=10)
exp.save_to_file(os.path.join(SAVE_DIR,"BiGRU_LIME_Explanation.html"))
print("Done")

