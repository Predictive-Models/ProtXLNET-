def train_validate(model, train_loader, val_loader):

    criterion = nn.CrossEntropyLoss()

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=BEST_LR,
        weight_decay=BEST_WD
    )

    tr_loss, val_loss, tr_acc, val_acc = [], [], [], []

    for _ in range(EPOCHS):

        # TRAIN
        model.train()
        loss_sum, correct, total = 0, 0, 0

        for xb, yb in train_loader:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)

            optimizer.zero_grad()
            out = model(xb)
            loss = criterion(out, yb)

            loss.backward()
            optimizer.step()

            loss_sum += loss.item() * xb.size(0)
            correct += (out.argmax(1) == yb).sum().item()
            total += yb.size(0)

        tr_loss.append(loss_sum / total)
        tr_acc.append(correct / total)

        # VALIDATION
        model.eval()
        loss_sum, correct, total = 0, 0, 0

        with torch.no_grad():
            for xb, yb in val_loader:
                xb, yb = xb.to(DEVICE), yb.to(DEVICE)
                out = model(xb)
                loss = criterion(out, yb)

                loss_sum += loss.item() * xb.size(0)
                correct += (out.argmax(1) == yb).sum().item()
                total += yb.size(0)

        val_loss.append(loss_sum / total)
        val_acc.append(correct / total)

    return tr_loss, val_loss, tr_acc, val_acc

