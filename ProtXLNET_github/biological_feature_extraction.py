# ============================
# Clean sequence: replace unknown AA with 'A'
# ============================
def clean_sequence(seq):
    standard_aa = set("ACDEFGHIKLMNPQRSTVWY")
    return "".join([aa if aa in standard_aa else "A" for aa in seq.upper()])

# ============================
# Feature extraction
# ============================
def extract_features(seq):
    seq = clean_sequence(seq)
    analysis = ProteinAnalysis(seq)

    # 1- Hydrophobicity
    hydro = analysis.gravy()
    # 2- Net charge
    charge = analysis.charge_at_pH(7.0)
    # 3- Kidera factors
    kid = np.zeros(10)
    count = 0
    for aa in seq:
        if aa in KIDERA:
            kid += np.array(KIDERA[aa])
            count += 1
    kid /= max(count,1)
    # 4- BLOSUM62 (average over sequence)
    blosum = 0
    for s in seq:
        blosum += blosum62[(s,s)]
    blosum /= len(seq)
    # 5- Molecular weight
    mw = molecular_weight(seq, "protein")
    # 6- Sequence length
    seqlen = len(seq)

    features = [hydro, charge] + kid.tolist() + [blosum, mw, seqlen]
    return np.array(features)

# ============================
# Load CSV
# ============================
df = pd.read_csv("independent_test_final_input.csv")   # columns: seq1, seq2, label
df = df.dropna(subset=["seq1", "seq2"]).reset_index(drop=True)

X = []
y = df["label"].values

# ============================
# Feature extraction + sum fusion
# ============================
for i, row in df.iterrows():
    f1 = extract_features(row["seq1"])
    f2 = extract_features(row["seq2"])
    fused = f1 + f2  # sum fusion
    X.append(fused)

X = np.array(X)
print("Feature shape:", X.shape)  # (num_pairs, 15)

# ============================
