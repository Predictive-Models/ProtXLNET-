import pandas as pd
import subprocess

# ==============================
# FILES
# ==============================

TRAIN_FILE = "human_filtered_dataset 0.4.csv"
TEST_FILE = "merged_human_output (1).csv"

TRAIN_FASTA = "train_sequences.fasta"
TEST_FASTA = "test_sequences.fasta"

FILTERED_FASTA = "test_filtered_sequences.fasta"
FINAL_TEST = "independent_test_final_human.csv"

# ==============================
# STEP 1: LOAD DATA
# ==============================

train = pd.read_csv(TRAIN_FILE)
test = pd.read_csv(TEST_FILE)

print("Train pairs:", len(train))
print("Test pairs:", len(test))

# ==============================
# STEP 2: EXTRACT UNIQUE SEQS
# ==============================

train_seqs = set(train["seq1"]).union(set(train["seq2"]))
test_seqs = set(test["seq1"]).union(set(test["seq2"]))

print("Unique train sequences:", len(train_seqs))
print("Unique test sequences:", len(test_seqs))

# ==============================
# STEP 3: WRITE FASTA FILES
# ==============================

with open(TRAIN_FASTA, "w") as f:
    for i, seq in enumerate(train_seqs):
        f.write(f">train_{i}\n{seq}\n")

with open(TEST_FASTA, "w") as f:
    for i, seq in enumerate(test_seqs):
        f.write(f">test_{i}\n{seq}\n")

print("FASTA files created")

# ==============================
# STEP 4: RUN CD-HIT-2D
# ==============================

cmd = [
    "cd-hit-2d",
    "-i", TRAIN_FASTA,
    "-i2", TEST_FASTA,
    "-o", FILTERED_FASTA,
    "-c", "0.4",
    "-n", "2",
    "-T", "8",
    "-M", "16000",
    "-d", "0"
]
print("Running CD-HIT-2D...")
subprocess.run(cmd, check=True)

print("CD-HIT-2D finished")

# ==============================
# STEP 5: READ FILTERED TEST SEQS
# ==============================

filtered = set()

with open(FILTERED_FASTA) as f:
    for line in f:
        if not line.startswith(">"):
            filtered.add(line.strip())

print("Remaining independent sequences:", len(filtered))

# ==============================
# STEP 6: REBUILD VALID TEST PAIRS
# ==============================

test_final = test[
    test["seq1"].isin(filtered) &
    test["seq2"].isin(filtered)
]

test_final.to_csv(FINAL_TEST, index=False)

print("Final independent test pairs:", len(test_final))
print("Saved:", FINAL_TEST)

import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA

# =========================
# USER SETTINGS
# =========================
INPUT_CSV = "human_protxlnet_len100_embeddings.csv"
OUT_CSV = "human_protxlnet_PCA.csv"

SEQ_FEATURES = 1024
PCA_DIM = 50

# =========================
# LOAD DATA
# =========================
df = pd.read_csv(INPUT_CSV)
print("Original shape:", df.shape)

# =========================
# SPLIT FEATURES & LABEL
# =========================
X = df.iloc[:, :-1].values
y = df.iloc[:, -1].values

assert X.shape[1] == 2 * SEQ_FEATURES, \
    "Expected 2048 features (1024 per sequence)"

# =========================
# SEQ1 / SEQ2 SPLIT
# =========================
X_seq1 = X[:, :SEQ_FEATURES]
X_seq2 = X[:, SEQ_FEATURES:]

# =========================
# STANDARDIZE (SEPARATELY)
# =========================
scaler1 = StandardScaler()
scaler2 = StandardScaler()

X_seq1_scaled = scaler1.fit_transform(X_seq1)
X_seq2_scaled = scaler2.fit_transform(X_seq2)

# =========================
# PCA PER SEQUENCE
# =========================
pca1 = PCA(n_components=PCA_DIM, random_state=42)
pca2 = PCA(n_components=PCA_DIM, random_state=42)

X_seq1_pca = pca1.fit_transform(X_seq1_scaled)
X_seq2_pca = pca2.fit_transform(X_seq2_scaled)

print("Seq1 PCA shape:", X_seq1_pca.shape)
print("Seq2 PCA shape:", X_seq2_pca.shape)

print("Seq1 variance:", np.sum(pca1.explained_variance_ratio_))
print("Seq2 variance:", np.sum(pca2.explained_variance_ratio_))

# =========================
# CONCATENATE
# =========================
X_final = np.concatenate([X_seq1_pca, X_seq2_pca], axis=1)

print("Final feature shape:", X_final.shape)  # (N, 100)

# =========================
# SAVE CSV
# =========================
cols = (
    [f"seq1_PC{i+1}" for i in range(PCA_DIM)] +
    [f"seq2_PC{i+1}" for i in range(PCA_DIM)]
)

df_out = pd.DataFrame(X_final, columns=cols)
df_out["label"] = y

df_out.to_csv(OUT_CSV, index=False)
print(f"PCA features saved → {OUT_CSV}")

