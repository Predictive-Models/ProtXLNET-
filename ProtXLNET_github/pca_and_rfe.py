import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.impute import SimpleImputer

# =========================
# USER SETTINGS NAN safe code
# =========================
INPUT_CSV = "human_protxlnet_len100_embeddings.csv"
OUT_CSV = "human_protxlnet_PCA_mouse.csv"

SEQ_FEATURES = 1024
PCA_DIM = 50

# =========================
# LOAD DATA
# =========================
df = pd.read_csv(INPUT_CSV)
print("Original shape:", df.shape)

# =========================
# SPLIT FEATURES & LABEL
# =========================
X = df.iloc[:, :-1].values
y = df.iloc[:, -1].values

assert X.shape[1] == 2 * SEQ_FEATURES, \
    "Expected 2048 features (1024 per sequence)"

# =========================
# REPLACE INF WITH NaN
# =========================
X = np.where(np.isinf(X), np.nan, X)

print("Total NaN values:", np.isnan(X).sum())

# =========================
# IMPUTE NaN VALUES
# =========================
imputer = SimpleImputer(strategy="mean")
X = imputer.fit_transform(X)

print("NaN after imputation:", np.isnan(X).sum())

# =========================
# SEQ1 / SEQ2 SPLIT
# =========================
X_seq1 = X[:, :SEQ_FEATURES]
X_seq2 = X[:, SEQ_FEATURES:]

# =========================
# STANDARDIZE
# =========================
scaler1 = StandardScaler()
scaler2 = StandardScaler()

X_seq1_scaled = scaler1.fit_transform(X_seq1)
X_seq2_scaled = scaler2.fit_transform(X_seq2)

# =========================
# PCA PER SEQUENCE
# =========================
pca1 = PCA(n_components=PCA_DIM, random_state=42)
pca2 = PCA(n_components=PCA_DIM, random_state=42)

X_seq1_pca = pca1.fit_transform(X_seq1_scaled)
X_seq2_pca = pca2.fit_transform(X_seq2_scaled)

print("Seq1 PCA shape:", X_seq1_pca.shape)
print("Seq2 PCA shape:", X_seq2_pca.shape)

print("Seq1 variance:", np.sum(pca1.explained_variance_ratio_))
print("Seq2 variance:", np.sum(pca2.explained_variance_ratio_))

# =========================
# CONCATENATE FEATURES
# =========================
X_final = np.concatenate([X_seq1_pca, X_seq2_pca], axis=1)

print("Final feature shape:", X_final.shape)

# =========================
# SAVE CSV
# =========================
cols = (
    [f"seq1_PC{i+1}" for i in range(PCA_DIM)] +
    [f"seq2_PC{i+1}" for i in range(PCA_DIM)]
)

df_out = pd.DataFrame(X_final, columns=cols)
df_out["label"] = y

df_out.to_csv(OUT_CSV, index=False)

print(f"PCA features saved → {OUT_CSV}")

import pandas as pd
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.feature_selection import RFE

# ======================
# Load CSV file
# ======================
df = pd.read_csv("Hybrid Mouse Train.csv")

X = df.iloc[:, :-1].values   # features
y = df.iloc[:, -1].values    # class labels (last column)

# ======================
# Scale features
# ======================
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# ======================
# SVM + RFE feature selection
# ======================
svm = SVC(kernel="linear", C=1)

rfe = RFE(
    estimator=svm,
    n_features_to_select=20,
    step=5
)

X_selected = rfe.fit_transform(X_scaled, y)

# ======================
# Save selected features
# ======================
selected_feature_names = df.columns[:-1][rfe.support_]

df_selected = pd.DataFrame(X_selected, columns=selected_feature_names)
df_selected["Label"] = y

df_selected.to_csv("Hybrid XLNET SVM RFE Mouse Train.csv", index=False)

print("✅ CSV loaded and selected features saved successfully!")
print("Final shape:", df_selected.shape)