import pandas as pd
import networkx as nx


def compute_pairwise_topological_features_sum(
    pair_csv,
    save_csv=None,
    interaction_label=1
):
    """
    Compute SUM-fused weighted topological features
    from protein1, protein2, label CSV.
    """

    # -----------------------------
    # Step 1: Load pair file
    # -----------------------------
    df_pairs = pd.read_csv(pair_csv)

    # Updated column names
    expected_cols = {"seq1", "seq2", "label"}
    if not expected_cols.issubset(df_pairs.columns):
        raise ValueError(
            f"CSV must contain columns {expected_cols}, "
            f"but found {df_pairs.columns.tolist()}"
        )

    # -----------------------------
    # Step 2: Build graph (ONLY positives)
    # -----------------------------
    G = nx.Graph()

    for _, row in df_pairs.iterrows():
        if row["label"] == interaction_label:
            # Binary interaction graph
            G.add_edge(row["seq1"], row["seq2"], weight=1.0)

    print(f"Graph built with {G.number_of_nodes()} nodes "
          f"and {G.number_of_edges()} edges")

    # -----------------------------
    # Step 3: Node-level weighted topology
    # -----------------------------
    node_features = {}

    node_features["degree"] = dict(G.degree(weight="weight"))
    node_features["clustering"] = nx.clustering(G, weight="weight")
    node_features["betweenness"] = nx.betweenness_centrality(G, weight="weight")
    node_features["closeness"] = nx.closeness_centrality(G, distance="weight")
    node_features["pagerank"] = nx.pagerank(G, weight="weight")

    try:
        node_features["eigenvector"] = nx.eigenvector_centrality(
            G, weight="weight", max_iter=1000
        )
    except nx.PowerIterationFailedConvergence:
        node_features["eigenvector"] = {n: 0.0 for n in G.nodes()}

    node_features["load_centrality"] = nx.load_centrality(G, weight="weight")

    try:
        node_features["eccentricity"] = nx.eccentricity(
            G, sp=dict(nx.shortest_path_length(G, weight="weight"))
        )
    except nx.NetworkXError:
        node_features["eccentricity"] = {n: 0.0 for n in G.nodes()}

    node_features["avg_neighbor_degree"] = nx.average_neighbor_degree(
        G, weight="weight"
    )

    node_features["triangles"] = nx.triangles(G)
    node_features["core_number"] = nx.core_number(G)

    density = nx.density(G)

    # -----------------------------
    # Step 4: Pairwise SUM fusion
    # -----------------------------
    rows = []

    for _, row in df_pairs.iterrows():
        p1, p2, label = row["seq1"], row["seq2"], row["label"]

        fused = {
            "seq1": p1,
            "seq2": p2,
            "label": label,
            "density": density
        }

        for feat_name, feat_dict in node_features.items():
            f1 = feat_dict.get(p1, 0.0)
            f2 = feat_dict.get(p2, 0.0)

            fused[f"{feat_name}_sum"] = f1 + f2

        rows.append(fused)

    df_out = pd.DataFrame(rows)

    # -----------------------------
    # Step 5: Save
    # -----------------------------
    if save_csv:
        df_out.to_csv(save_csv, index=False)
        print(f"✅ Pairwise SUM topological features saved to: {save_csv}")

    return df_out


